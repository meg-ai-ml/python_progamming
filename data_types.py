# This program shows how to find out the type of data stored in a variable.


name = "Meghana" # String
roll_no = 7 # Integer
percentage = 99.9 # Float
present = True # Boolean

print(type(name)) # <class 'str'>
print(type(roll_no)) # <class 'int'>
print(type(percentage)) # <class 'float'>
print(type(present)) # <class 'bool'>
